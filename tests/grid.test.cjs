const assert=require('node:assert/strict');
require('../VoltCalc_Guiado/model.js');
global.window=globalThis;
require('../VoltCalc_Guiado/technical.js');
const M=VoltModel,G=VoltGrid;
const first=M.newCircuit();first.description='Original';
const rows=G.paste([first],'loads',0,0,'C1\tRua\tfn\tA\t15\t100\tW\t1\t50\r\nC2\tGaragem\tff\tAB\t2\t200\tW\t0,97\t20\r\n');
assert.equal(rows.length,2);assert.equal(rows[1].loads[0].powerFactor,'0.97');
assert.equal(first.description,'Original');assert.equal(rows[0].id,first.id);
assert.notEqual(rows[0].id,rows[1].id);assert.equal(rows[1].phaseSet,'AB');
rows[0].loads.push(M.newLoad());
const before=structuredClone(rows);
assert.throws(()=>G.paste(rows,'loads',0,1,'Mudado\tfn\tA\t20'),/vários grupos/);
assert.deepEqual(rows,before);
assert.throws(()=>G.paste(rows,'loads',0,8,'20\t30'),/ultrapassa/);
assert.throws(()=>G.paste(rows,'loads',299,0,'a\nb'),/300/);
assert.throws(()=>G.paste(rows,'loads',1,5,'1.000,50'),/separador/);
assert.throws(()=>G.paste(rows,'loads',1,2,'bifase inventada'),/desconhecida/);
const pending=G.paste(rows,'conditions',1,2,'\t1\tbundle\t4\tverify\t10\t1,45');
assert.equal(pending[1].temperature,'');assert.equal(pending[1].breakerMode,'verify');
const clone=structuredClone(first);clone.methodOverride='C';clone.unknownInstallation=true;
G.set(clone,G.columns.installation[3],'conduit');
assert.equal(clone.methodOverride,'');assert.equal(clone.unknownInstallation,false);
G.set(clone,G.columns.loads[5],'-',false);assert.equal(clone.loads[0].power,'-');
const backup=M.readProject(M.projectData({projectName:'Grade',circuits:rows,draft:rows[0],editingId:rows[0].id,supply:M.supplyDefaults(),reactance:.08}),true);
assert.equal(backup.circuits[0].loads.length,2);
console.log('Grid: colagem atômica, limites, números, grupos e backup OK.');
