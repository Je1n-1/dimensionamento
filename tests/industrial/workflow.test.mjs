import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createEntity} from '../../frontend/industrial/js/core/model.js';
import {copyConsumer,suggestedPowerBasis,upsertConsumer} from '../../frontend/industrial/js/core/consumers.js';
import {consumerForm} from '../../frontend/industrial/js/consumers-view.js';
import {conductorsView} from '../../frontend/industrial/js/conductors-view.js';
import {preparationForm} from '../../frontend/industrial/js/topology-view.js';
const contract=JSON.parse(fs.readFileSync(new URL('../../data/industrial/contracts.v9.json',import.meta.url)));
const entity=(name,data={})=>createEntity(contract,name,data);
let p=entity('Project',{name:'UX'});
const c=entity('Consumer',{tag:'M1',type:'motor',power:15,unit:'cv',powerBasis:'mechanical',distance:20,distanceBasis:'cumulative'});
p=upsertConsumer(contract,p,c,entity('Motor',{nominalConditionsConfirmed:true,plateCurrent:30}));
const before=structuredClone(p), duplicate=copyConsumer(contract,p,c.id);
assert.deepEqual(p,before);
assert.notEqual(duplicate.consumer.id,c.id);
assert.notEqual(duplicate.motor.id,p.motors[0].id);
assert.equal(duplicate.motor.nominalConditionsConfirmed,null);
assert.equal(duplicate.consumer.distance,20);
assert.equal(duplicate.consumer.plannedSegmentId,null);
p=upsertConsumer(contract,p,duplicate.consumer,duplicate.motor);
assert.equal(p.consumers.length,2);assert.equal(p.circuits.length,0);
assert.notEqual(copyConsumer(contract,p,c.id).consumer.tag,duplicate.consumer.tag);
assert.equal(suggestedPowerBasis('VA','lighting'),'apparent');
assert.equal(suggestedPowerBasis('kW','motor'),'mechanical');
assert.equal(suggestedPowerBasis('W','lighting'),'electrical');
assert.equal(suggestedPowerBasis('hp','other'),'mechanical');
const form=consumerForm(p,{...c,installationMethod:'Legado'},p.motors[0],true);
assert.ok(form.includes('Legado — valor cadastrado'));
assert.ok(form.includes('220 V não define a ligação'));
assert.ok(form.includes('Catálogo e identificação do motor (opcional)'));
assert.equal((form.match(/name="motor.currentPreference"/g)||[]).length,1);
const view=conductorsView(p);
assert.ok(view.includes('M1'));
assert.ok(view.includes('falta vincular a um circuito'));
assert.match(view,/data-conductor-action="calculate" disabled/);
assert.ok(!view.includes('Conforme'));
assert.ok(preparationForm(p).includes('sem compartilhar trechos físicos'));
console.log('Industrial workflow: copying, contextual forms and pending loads passed.');
