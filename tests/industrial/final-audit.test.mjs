import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {validateEntity} from '../../frontend/industrial/js/core/model.js';
import {LocalProjectRepository} from '../../frontend/industrial/js/core/local-repository.js';
import {projectBackup,readProjectBackup} from '../../frontend/industrial/js/core/project-files.js';
import {createStore} from '../../frontend/industrial/js/core/state.js';
import {upsertConsumer} from '../../frontend/industrial/js/core/consumers.js';
import {ReportService} from '../../frontend/industrial/js/core/reports.js';
import {infrastructureView} from '../../frontend/industrial/js/infrastructure-view.js';
import {conductorsView} from '../../frontend/industrial/js/conductors-view.js';

const contract=JSON.parse(fs.readFileSync(new URL('../../data/industrial/contracts.v9.json',import.meta.url)));
const previous=[8,7,6,5,4,3,2].map(v=>JSON.parse(fs.readFileSync(new URL(`../../data/industrial/contracts.v${v}.json`,import.meta.url))));
const py=(code,input)=>JSON.parse(execFileSync('python',['-X','utf8','-c',code],{input:input===undefined?undefined:JSON.stringify(input),encoding:'utf8',maxBuffer:20*1024*1024}));
const p=py("import sys,json;sys.path.insert(0,'tests');from industrial.audit_fixture import installation;print(json.dumps(installation()))");
assert.deepEqual(validateEntity(contract,'Project',p),[]);
const memory=new Map([['residential','preserved']]);
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const locks={request:async(_k,_o,f)=>f()};
const repo=new LocalProjectRepository(contract,{storage,locks,previousContract:previous});
const saved=await repo.save(p,0),backup=projectBackup(contract,saved);
await repo.setCurrentId(null);
const reopened=new LocalProjectRepository(contract,{storage,locks,previousContract:previous});
assert.deepEqual(await reopened.load(saved.id),saved);
const duplicate=await reopened.duplicate(saved.id,saved.storageRevision);
assert.equal(duplicate.consumers.length,30);assert.equal(duplicate.panels.length,4);
const originalIds=new Set(['consumers','motors','panels','nodes','segments','circuits','cables','conductors','infrastructures'].flatMap(k=>saved[k].map(x=>x.id)));
for(const collection of ['consumers','motors','panels','nodes','segments','circuits','cables','conductors','infrastructures'])
  for(const item of duplicate[collection])assert.ok(!originalIds.has(item.id));
assert.deepEqual(validateEntity(contract,'Project',duplicate),[]);
await reopened.delete(duplicate.id,duplicate.storageRevision);
await assert.rejects(()=>reopened.load(duplicate.id),{code:'NOT_FOUND'});
assert.deepEqual(await reopened.load(saved.id),saved);
const recovered=await reopened.importProject(readProjectBackup(contract,previous,backup));
assert.equal(recovered.segments.length,33);assert.deepEqual(recovered.nodes.map(n=>n.position),saved.nodes.map(n=>n.position));
assert.equal(memory.get('residential'),'preserved');
const reportService=new ReportService(contract,async(_url,o)=>({ok:true,json:async()=>py("import sys,json;from voltcalc.industrial.reports import report_request;print(json.dumps(report_request(json.load(sys.stdin))))",JSON.parse(o.body))}));
const originalReport=(await reportService.generate(saved)).report;
assert.ok(infrastructureView(saved).includes('Quadro QD-1'),'feeder destination is a panel, not a missing load');
const analysis=py("import sys,json;from voltcalc.industrial.conductors import calculate_project;print(json.dumps(calculate_project(json.load(sys.stdin))))",saved);
const conductorHTML=conductorsView(saved,{analysis});
assert.ok(!conductorHTML.includes('Queda de tensão: não calculada (Etapa 8)'));
assert.ok(conductorHTML.includes('têm análises próprias'));
const recoveredReport=(await reportService.generate(recovered)).report;
assert.deepEqual(recoveredReport.summary,originalReport.summary);
assert.deepEqual(recoveredReport.diagram.nodes.map(({id,...n})=>n),originalReport.diagram.nodes.map(({id,...n})=>n));
const store=createStore(contract);store.setDraft(saved);
const token=store.token('currents');
const current=py("import sys,json;from voltcalc.industrial.currents import calculate_project;print(json.dumps(calculate_project(json.load(sys.stdin))[0]))",saved);
assert.ok(store.acceptResult(token,current));
const edit=structuredClone(saved.consumers[0]);edit.power=6;
const changed=upsertConsumer(contract,store.snapshot(),edit,saved.motors[0]);store.setDraft(changed);
assert.equal(changed.revision,saved.revision+1);
assert.equal(changed.results[0].status,'invalidated');
assert.ok(changed.cables.every(c=>c.design.manualIbConfirmed===null&&c.design.scopeConfirmed===null));
assert.equal(store.acceptResult(token,current),false);
assert.deepEqual(await reopened.load(saved.id),saved,'unsaved mutation cannot modify persisted source');
console.log('Stage 11: 30 consumers / 4 panels / 33 segments; save, close, reopen, duplicate, delete isolated copy, import recovery, equal recalculation, motor edit invalidation and residential preservation passed.');
