import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createEntity,validateEntity} from '../../frontend/industrial/js/core/model.js';
import {upsertConsumer,upsertMotorBatch} from '../../frontend/industrial/js/core/consumers.js';
import {consumerForm,motorBatchRow} from '../../frontend/industrial/js/consumers-view.js';
const contract=JSON.parse(fs.readFileSync(new URL('../../data/industrial/contracts.v9.json',import.meta.url)));
const entity=(name,data={})=>createEntity(contract,name,data);
const p=entity('Project',{name:'Motores individuais'});
const base=entity('Consumer',{type:'motor',quantity:3,tag:'Base',power:10,unit:'cv',powerBasis:'mechanical',voltage:380,connection:'3F',phaseSet:'ABC',distance:10,distanceBasis:'cumulative'});
const motor=entity('Motor',{plateCurrent:15,nominalConditionsConfirmed:true});
const rows=[{consumer:{tag:'M1'},motor:{}},{consumer:{tag:'M2',distance:30,power:20},motor:{plateCurrent:29}},{consumer:{tag:'M3',voltage:220,connection:'FF',phaseSet:'AB'},motor:{}}];
const original=structuredClone(p), q=upsertMotorBatch(contract,p,base,motor,rows);
assert.deepEqual(p,original);
assert.deepEqual(validateEntity(contract,'Project',q),[]);
assert.deepEqual(q.consumers.map(c=>c.quantity),[1,1,1]);
assert.deepEqual(q.consumers.map(c=>c.distance),[10,30,10]);
assert.deepEqual(q.consumers.map(c=>c.power),[10,20,10]);
assert.deepEqual(q.motors.map(m=>m.plateCurrent),[15,29,15]);
assert.ok(q.motors.every(m=>m.nominalConditionsConfirmed===null));
assert.equal(new Set(q.consumers.map(c=>c.id)).size,3);
assert.equal(new Set(q.motors.map(m=>m.id)).size,3);
assert.equal(q.revision,p.revision+1);
assert.equal(q.circuits.length,0);
assert.equal(q.consumers[2].connection,'FF');
for(const bad of [rows.map((r,i)=>i===2?{...r,consumer:{tag:'M1'}}:r),rows.map((r,i)=>i===1?{...r,consumer:{tag:'M2',power:-1}}:r)]) {
  assert.throws(()=>upsertMotorBatch(contract,p,base,motor,bad),/Motor [23]/);
  assert.deepEqual(p,original);
}
assert.throws(()=>upsertMotorBatch(contract,p,{...base,quantity:151},motor,rows),/2 a 150/);
const old=upsertConsumer(contract,p,base,motor);
const split=upsertMotorBatch(contract,old,base,old.motors[0],rows);
assert.equal(split.consumers.length,3);
assert.equal(split.consumers[0].id,base.id);
assert.equal(split.motors.length,3);
const linked=structuredClone(old);
linked.nodes.push(entity('Node',{kind:'consumer',entityId:base.id,label:'Motor original'}));
assert.throws(()=>upsertMotorBatch(contract,linked,base,motor,rows),/vinculado/);
assert.equal(linked.consumers.length,1);
const single=consumerForm(p,{...base,quantity:1},motor,false);
assert.match(single,/id="consumer-motor-batch" hidden disabled/);
const row=motorBatchRow(p,1,'<Motor>');
assert.ok(row.includes('&lt;Motor&gt;'));
assert.ok(row.includes('batch.1.motor.plateCurrent'));
assert.ok(row.includes('Usar dados comuns'));
console.log('Motor batch: independent records, inherited/overridden data, atomic failures, existing links and single layout passed.');
